import { NextRequest, NextResponse } from 'next/server';
import { createAIService } from '@/utils/ai';
import { ApiResponse } from '@/types';
import JSZip from 'jszip';

// Simplified HTML/CSS/JS code generation
interface CodeData {
  html?: string;
  css?: string;
  javascript?: string;
  readme?: string;
}

// eslint-disable-next-line @typescript-eslint/no-unused-vars
async function createCodeZip(codeData: CodeData): Promise<Buffer> {
  const zip = new JSZip();
  
  // Add main HTML file
  if (codeData.html) {
    zip.file('index.html', codeData.html);
  }

  // Add CSS file
  if (codeData.css) {
    zip.file('styles.css', codeData.css);
  }

  // Add JavaScript file
  if (codeData.javascript) {
    zip.file('script.js', codeData.javascript);
  }

  // Add README file
  if (codeData.readme) {
    zip.file('README.txt', codeData.readme);
  }

  // Add package.json for easy local development
  const projectName = 'laygen-generated-app';
  
  zip.file('package.json', JSON.stringify({
    name: projectName.toLowerCase().replace(/\s+/g, '-'),
    version: '1.0.0',
    description: `${projectName} application generated by Laygen AI`,
    main: 'index.html',
    scripts: {
      start: 'python -m http.server 8000',
      'start-node': 'npx http-server -p 8000',
      'open': 'open index.html'
    },
    keywords: ['html', 'css', 'javascript', 'web-app'],
    author: 'Laygen AI',
    license: 'MIT'
  }, null, 2));

  // Add README with features
  const features = ['Dynamic functionality', 'Responsive design', 'Modern UI', 'Interactive elements'];
  
  zip.file('README.md', `# ${projectName}

Generated by Laygen AI - From Requirements to Ready UI

## Features

${features.map(feature => `- ${feature}`).join('\n')}

## Getting Started

### Quick Start (Recommended)
Simply open \`index.html\` in your web browser! No installation required.

### Local Development Server
If you want to run it on a local server:

#### Option 1: Python
\`\`\`bash
python -m http.server 8000
\`\`\`

#### Option 2: Node.js
\`\`\`bash
npx http-server -p 8000
\`\`\`

#### Option 3: Live Server (VS Code Extension)
Right-click on \`index.html\` and select "Open with Live Server"

## Usage

1. Open \`index.html\` in your web browser
2. Start using your application immediately!
3. All functionality is built-in and ready to use

## Generated Files

- \`index.html\` - Main application file (open this in your browser)
- \`styles.css\` - All CSS styles
- \`script.js\` - JavaScript functionality
- \`README.txt\` - Application documentation
- \`package.json\` - Project configuration

---
Generated by Laygen AI - Transform your requirements into ready UI instantly!
`);

  // Generate the ZIP file as a buffer
  const zipBuffer = await zip.generateAsync({ type: 'nodebuffer' });
  return zipBuffer;
}

export async function POST(request: NextRequest) {
  console.log('💻 [CODE API] Starting code generation process...');
  const startTime = Date.now();
  
  try {
    console.log('📥 [CODE API] Extracting request data...');
    const { layoutData, framework = 'html' } = await request.json();
    
    console.log('📋 [CODE API] Request data:', {
      hasLayoutData: !!layoutData,
      framework: framework,
      layoutDataKeys: layoutData ? Object.keys(layoutData) : []
    });
    
    if (!layoutData) {
      console.log('❌ [CODE API] No layout data provided');
      return NextResponse.json<ApiResponse<null>>({
        success: false,
        error: 'Layout data is required'
      }, { status: 400 });
    }

    // Initialize AI service
    console.log('🤖 [CODE API] Creating AI service for code generation...');
    const aiService = createAIService();
    console.log('✅ [CODE API] AI service created successfully');
    
    // Check which AI service is being used
    const serviceType = aiService.constructor.name;
    console.log('🎯 [CODE API] Using AI service:', serviceType);
    
    if (serviceType.includes('Perplexity')) {
      console.log('🚀 [CODE API] Perplexity AI is PRIMARY service - Enhanced code generation!');
    } else {
      console.log('⚠️ [CODE API] Using fallback AI service:', serviceType);
    }
    
    // Generate code
    console.log('🧠 [CODE API] Generating code with AI service...');
    console.log('📝 [CODE API] Framework:', framework);
    console.log('📊 [CODE API] Layout data summary:', {
      hasDataAnalysis: !!layoutData.dataAnalysis,
      hasSelectedColors: !!layoutData.selectedColors,
      description: layoutData.dataAnalysis?.description?.substring(0, 100) + '...',
      colors: layoutData.selectedColors ? Object.keys(layoutData.selectedColors) : []
    });
    
    const result = await aiService.generateCode(layoutData, framework);

    if (!result.success) {
      console.log('❌ [CODE API] AI code generation failed:', result.error);
      return NextResponse.json<ApiResponse<null>>({
        success: false,
        error: result.error
      }, { status: 500 });
    }

    console.log('✅ [CODE API] Code generated successfully by AI');
    console.log('📊 [CODE API] AI generation result:', {
      success: result.success,
      hasLayoutData: !!result.layoutData,
      confidence: result.confidence
    });
    
    // Log which AI service was used
    if (serviceType.includes('Perplexity')) {
      console.log('🚀 [CODE API] Perplexity AI generation completed successfully!');
    } else {
      console.log('⚠️ [CODE API] Fallback AI service generation completed');
    }
    
    // Extract the simplified code data
    const codeData = result.layoutData as CodeData;
    console.log('📁 [CODE API] Generated code structure:', {
      hasHtml: !!codeData.html,
      hasCss: !!codeData.css,
      hasJavascript: !!codeData.javascript,
      hasReadme: !!codeData.readme
    });

    // Validate generated code
    const htmlLength = codeData.html?.length || 0;
    const cssLength = codeData.css?.length || 0;
    const jsLength = codeData.javascript?.length || 0;
    const readmeLength = codeData.readme?.length || 0;

    console.log('📊 [CODE API] Code validation:', {
      htmlLength,
      cssLength,
      jsLength,
      readmeLength,
      totalLength: htmlLength + cssLength + jsLength + readmeLength
    });

    // Log content lengths for debugging
    console.log('📊 [CODE API] Generated content lengths:', {
      htmlLength,
      cssLength,
      jsLength,
      readmeLength
    });

    const processingTime = Date.now() - startTime;
    console.log('✅ [CODE API] Code generation completed successfully in', processingTime, 'ms');
    console.log('📊 [CODE API] Final validation passed - substantial code generated');

    // Return the same structure as test-ai-code API
    return NextResponse.json({
      success: true,
      data: codeData,
      isAIGenerated: true,
      message: 'Code generated successfully'
    });

  } catch (error) {
    const processingTime = Date.now() - startTime;
    console.error('❌ [CODE API] Code generation error after', processingTime, 'ms:', error);
    
    // Provide more specific error messages
    let errorMessage = 'Internal server error';
    if (error instanceof Error) {
      errorMessage = error.message;
      console.error('🔍 [CODE API] Error details:', {
        message: error.message,
        stack: error.stack?.substring(0, 500),
        name: error.name
      });
    }
    
    return NextResponse.json({
      success: false,
      error: errorMessage,
      isAIGenerated: false
    }, { status: 500 });
  }
}
