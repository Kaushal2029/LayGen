'use client';

import { useState } from 'react';
import Image from 'next/image';

export default function TestDeepAIPage() {
  const [prompt, setPrompt] = useState('A modern web dashboard with clean design');
  const [isLoading, setIsLoading] = useState(false);
  const [result, setResult] = useState<{
    imageUrl?: string;
    success?: boolean;
    error?: string;
    service?: string;
    processingTime?: number;
    data?: {
      message?: string;
    };
  } | null>(null);
  const [error, setError] = useState<string | null>(null);

  const handleTest = async () => {
    console.log('🧪 [TEST DEEPAI UI] Starting test...');
    setIsLoading(true);
    setError(null);
    setResult(null);

    try {
      const response = await fetch('/api/test-deepai', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({ prompt }),
      });

      const data = await response.json();
      console.log('📊 [TEST DEEPAI UI] Response:', data);

      if (data.success) {
        setResult(data);
      } else {
        setError(data.error || 'Test failed');
      }
    } catch (err: any) { // eslint-disable-line @typescript-eslint/no-explicit-any
      console.error('❌ [TEST DEEPAI UI] Error:', err);
      setError(err.message || 'Network error');
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="min-h-screen bg-gray-100 py-8">
      <div className="max-w-4xl mx-auto px-4">
        <h1 className="text-3xl font-bold text-gray-900 mb-8">
          DeepAI Image Generation Test
        </h1>
        
        <div className="bg-white rounded-lg shadow-md p-6 mb-6">
          <div className="mb-4">
            <label htmlFor="prompt" className="block text-sm font-medium text-gray-700 mb-2">
              Image Prompt
            </label>
            <input
              id="prompt"
              type="text"
              value={prompt}
              onChange={(e) => setPrompt(e.target.value)}
              className="w-full px-3 py-2 border border-gray-300 rounded-md focus:outline-none focus:ring-2 focus:ring-blue-500"
              placeholder="Enter a description for the image you want to generate"
            />
          </div>
          
          <button
            onClick={handleTest}
            disabled={isLoading || !prompt.trim()}
            className="bg-blue-600 text-white px-6 py-2 rounded-md hover:bg-blue-700 disabled:opacity-50 disabled:cursor-not-allowed"
          >
            {isLoading ? 'Generating...' : 'Generate Image'}
          </button>
        </div>

        {isLoading && (
          <div className="bg-blue-50 border border-blue-200 rounded-md p-4 mb-6">
            <div className="flex items-center">
              <div className="animate-spin rounded-full h-4 w-4 border-b-2 border-blue-600 mr-3"></div>
              <span className="text-blue-800">Generating image with DeepAI...</span>
            </div>
          </div>
        )}

        {error && (
          <div className="bg-red-50 border border-red-200 rounded-md p-4 mb-6">
            <h3 className="text-red-800 font-medium mb-2">Error</h3>
            <p className="text-red-700">{error}</p>
          </div>
        )}

        {result && (
          <div className="bg-green-50 border border-green-200 rounded-md p-6">
            <h3 className="text-green-800 font-medium mb-4">Success!</h3>
            
            <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
              <div>
                <h4 className="font-medium text-gray-900 mb-2">Generated Image</h4>
                {result.imageUrl && (
                  <Image
                    src={result.imageUrl}
                    alt="Generated by DeepAI"
                    width={400}
                    height={300}
                    className="w-full h-auto rounded-md shadow-sm"
                    onError={() => {
                      console.error('❌ [TEST DEEPAI UI] Image load error');
                    }}
                  />
                )}
              </div>
              
              <div>
                <h4 className="font-medium text-gray-900 mb-2">Response Details</h4>
                <div className="space-y-2 text-sm">
                  <div>
                    <span className="font-medium">Service:</span> {result.service}
                  </div>
                  <div>
                    <span className="font-medium">Processing Time:</span> {result.processingTime}ms
                  </div>
                  <div>
                    <span className="font-medium">Success:</span> {result.success ? 'Yes' : 'No'}
                  </div>
                  {result.data?.message && (
                    <div>
                      <span className="font-medium">Message:</span> {result.data.message}
                    </div>
                  )}
                </div>
              </div>
            </div>
            
            <div className="mt-4">
              <h4 className="font-medium text-gray-900 mb-2">Raw Response</h4>
              <pre className="bg-gray-100 p-3 rounded text-xs overflow-auto">
                {JSON.stringify(result, null, 2)}
              </pre>
            </div>
          </div>
        )}

        <div className="bg-yellow-50 border border-yellow-200 rounded-md p-4 mt-6">
          <h3 className="text-yellow-800 font-medium mb-2">Setup Instructions</h3>
          <ol className="text-yellow-700 text-sm space-y-1 list-decimal list-inside">
            <li>Get your DeepAI API key from: <a href="https://deepai.org/api-key" target="_blank" rel="noopener noreferrer" className="underline">https://deepai.org/api-key</a></li>
            <li>Add it to your <code className="bg-yellow-100 px-1 rounded">.env.local</code> file as <code className="bg-yellow-100 px-1 rounded">DEEPAI_API_KEY=your_key_here</code></li>
            <li>Restart your development server</li>
            <li>Test the image generation above</li>
          </ol>
        </div>
      </div>
    </div>
  );
}
